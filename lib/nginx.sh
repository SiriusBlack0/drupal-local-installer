#!/usr/bin/env bash

# ==================================================
# Nginx site for a project
#
# The site config follows the Drupal recipe from the Nginx docs:
# only index.php and update.php are executed, PHP inside files/ and
# vendor/ is refused, hidden files and private files are blocked.
# ==================================================

# Browsers and curl resolve *.localhost to ::1 (IPv6) first. A site that
# listens only on IPv4 is then skipped and the default site answers, so
# the project also listens on IPv6 whenever the system has it.
# NGINX_IPV6=0 or 1 overrides the detection (used by the tests).
is_ipv6_available() {
    case "${NGINX_IPV6:-auto}" in
        0) return 1 ;;
        1) return 0 ;;
        *) [[ -e /proc/net/if_inet6 ]] ;;
    esac
}

get_nginx_listen_directives() {
    printf '    listen 80;\n'

    if is_ipv6_available; then
        printf '    listen [::]:80;\n'
    fi
}

get_project_nginx_domain() {
    local machine_name="$1"

    printf '%s.localhost\n' "$machine_name"
}

generate_nginx_config() {
    local machine_name="$1"
    local project_dir="$2"
    local php_version="$3"

    local domain
    local socket
    local listen

    if [[ ! "$machine_name" =~ ^[a-z0-9_]+$ ]]; then
        echo "[ERROR] Invalid project machine name: $machine_name" >&2
        return 1
    fi

    if [[ ! "$php_version" =~ ^[0-9]+\.[0-9]+$ ]]; then
        echo "[ERROR] Invalid PHP version: $php_version" >&2
        return 1
    fi

    if [[ ! "$project_dir" =~ ^/[a-zA-Z0-9_./-]+$ || "$project_dir" == *".."* ]]; then
        echo "[ERROR] Invalid project directory: $project_dir" >&2
        return 1
    fi

    domain="$(get_project_nginx_domain "$machine_name")"
    socket="$(get_project_php_fpm_socket "$machine_name" "$php_version")"
    listen="$(get_nginx_listen_directives)"

    cat <<EOF_CONFIG
# Generated by drupal-local-installer for project: $machine_name
server {
$listen
    server_name $domain;

    root $project_dir/web;
    index index.php;

    access_log /var/log/nginx/${machine_name}.access.log;
    error_log /var/log/nginx/${machine_name}.error.log;

    client_max_body_size 64m;

    location = /favicon.ico {
        log_not_found off;
        access_log off;
    }

    location = /robots.txt {
        allow all;
        log_not_found off;
        access_log off;
    }

    # Text and log files are not served (robots.txt is matched above).
    location ~* \.(txt|log)\$ {
        deny all;
    }

    # PHP files in hidden directories.
    location ~ \..*/.*\.php\$ {
        return 403;
    }

    # Private files and PHP inside the public files directory.
    location ~ ^/sites/.*/private/ {
        return 403;
    }

    location ~ ^/sites/[^/]+/files/.*\.php\$ {
        deny all;
    }

    # Let's Encrypt and other well-known URIs stay reachable.
    location ~* ^/.well-known/ {
        allow all;
    }

    # Hidden files and directories (.git, .htaccess, .ht.sqlite, ...).
    location ~ (^|/)\. {
        return 403;
    }

    location / {
        try_files \$uri /index.php?\$query_string;
    }

    location @rewrite {
        rewrite ^ /index.php;
    }

    # PHP from vendor/ is never executed.
    location ~ /vendor/.*\.php\$ {
        deny all;
        return 404;
    }

    location ~ '\.php\$|^/update.php' {
        fastcgi_split_path_info ^(.+?\.php)(|/.*)\$;
        try_files \$fastcgi_script_name =404;
        include fastcgi_params;
        fastcgi_param HTTP_PROXY "";
        fastcgi_param SCRIPT_FILENAME \$document_root\$fastcgi_script_name;
        fastcgi_param PATH_INFO \$fastcgi_path_info;
        fastcgi_param QUERY_STRING \$query_string;
        fastcgi_intercept_errors on;
        fastcgi_pass unix:$socket;
    }

    # Image styles are generated by Drupal on first request.
    location ~ ^/sites/.*/files/styles/ {
        try_files \$uri @rewrite;
    }

    # Private file downloads are handled by Drupal.
    location ~ ^(/[a-z\-]+)?/system/files/ {
        try_files \$uri /index.php?\$query_string;
    }

    location ~* \.(js|css|png|jpg|jpeg|gif|ico|svg|webp|woff2?)\$ {
        try_files \$uri @rewrite;
        expires max;
        log_not_found off;
    }
}
EOF_CONFIG
}

get_nginx_config_path() {
    local machine_name="$1"

    printf '/etc/nginx/sites-available/%s.conf\n' "$machine_name"
}

get_nginx_enabled_path() {
    local machine_name="$1"

    printf '/etc/nginx/sites-enabled/%s.conf\n' "$machine_name"
}

nginx_config_exists() {
    local machine_name="$1"
    local config_path

    config_path="$(get_nginx_config_path "$machine_name")"

    [[ -e "$config_path" || -L "$config_path" ]]
}

# Writes the config to output_path (never replaces an existing file).
write_nginx_config() {
    local machine_name="$1"
    local project_dir="$2"
    local php_version="$3"
    local output_path="$4"
    local config

    if [[ -e "$output_path" || -L "$output_path" ]]; then
        printf 'Error: Configuration already exists: %s\n' "$output_path" >&2
        return 1
    fi

    # Generate first, so invalid input never leaves an empty file behind.
    config="$(generate_nginx_config "$machine_name" "$project_dir" "$php_version")" || return 1

    (
        set -C
        printf '%s\n' "$config" > "$output_path"
    )
}

# Installs and enables the site, checks the whole Nginx configuration
# with "nginx -t", and only then reloads Nginx. If the check fails, the
# new files are removed and the running Nginx is not touched.
install_nginx_site() {
    local machine_name="$1"
    local project_dir="$2"
    local php_version="$3"
    local available_path
    local enabled_path
    local temp_file

    available_path="$(get_nginx_config_path "$machine_name")"
    enabled_path="$(get_nginx_enabled_path "$machine_name")"

    if [[ -e "$available_path" || -L "$available_path" ||
          -e "$enabled_path" || -L "$enabled_path" ]]; then
        echo "[ERROR] Nginx configuration for '$machine_name' already exists."
        return 1
    fi

    temp_file="$(mktemp -u)"

    if ! write_nginx_config "$machine_name" "$project_dir" "$php_version" "$temp_file"; then
        rm -f "$temp_file"
        return 1
    fi

    if ! sudo install -m 0644 -o root -g root "$temp_file" "$available_path" ||
       ! sudo ln -s "$available_path" "$enabled_path"; then
        rm -f "$temp_file"
        sudo rm -f -- "$enabled_path" "$available_path"
        echo "[ERROR] Could not install the Nginx site."
        return 1
    fi

    rm -f "$temp_file"

    if ! run_logged "Checking Nginx configuration" sudo nginx -t; then
        sudo rm -f -- "$enabled_path" "$available_path"
        echo "[ERROR] The Nginx configuration test failed; the new site was removed."
        return 1
    fi

    if ! run_logged "Reloading Nginx" reload_or_start_service nginx; then
        sudo rm -f -- "$enabled_path" "$available_path"
        echo "[ERROR] Nginx could not reload; the new site was removed."
        return 1
    fi

    echo "[OK] Nginx site enabled: http://$(get_project_nginx_domain "$machine_name")"
}

remove_nginx_site() {
    local machine_name="$1"

    [[ "$machine_name" =~ ^[a-z0-9_]+$ ]] || return 1

    sudo rm -f -- \
        "$(get_nginx_enabled_path "$machine_name")" \
        "$(get_nginx_config_path "$machine_name")" &&
    reload_or_start_service nginx > /dev/null 2>&1
}

# Asks the site itself over HTTP, on IPv4 and (when available) IPv6,
# exactly like a browser would. Before site:install Drupal redirects to
# install.php; afterwards it answers with "X-Generator: Drupal".
is_drupal_answering_over() {
    local family="$1"
    local url="$2"

    curl "-$family" -sI --max-time 5 "$url/" 2>/dev/null |
        grep -qiE '^(x-generator: drupal|location: .*install\.php)'
}

# The URL is only shown to the user after it really answers, so the
# user never opens (and the browser never caches) a wrong page.
verify_nginx_site() {
    local machine_name="$1"
    local url
    local families="4"
    local family
    local attempt
    local failed=""

    url="http://$(get_project_nginx_domain "$machine_name")"

    if ! command -v curl > /dev/null; then
        echo "[WARNING] curl is not installed, so $url was not checked."
        echo "          Install curl and run ./start to check it."
        return 0
    fi

    if is_ipv6_available; then
        families="4 6"
    fi

    for family in $families; do
        # A reload finishes in the background; give Nginx a few seconds.
        for attempt in 1 2 3 4 5; do
            if is_drupal_answering_over "$family" "$url"; then
                continue 2
            fi

            if [[ "$attempt" -lt 5 ]]; then
                sleep 1
            fi
        done

        failed+=" IPv$family"
    done

    if [[ -n "$failed" ]]; then
        echo "[ERROR] $url does not answer as this Drupal site over:$failed"
        echo "        Another Nginx site may answer for this name. Check with:"
        echo "        sudo nginx -T | grep -nE 'listen|server_name'"
        return 1
    fi

    echo "[OK] $url answers (IPv${families// / and IPv})"
}
